"""Record reproducible source-correspondence evidence for a local build.

Checks installed wheel RECORD hashes and source archives without changing any
installed package. A successful check is evidence, not blanket legal clearance.
"""
import argparse
import ast
import base64
import csv
import hashlib
from importlib.metadata import distribution
import io
import json
from pathlib import Path
import platform
import re
import shlex
import subprocess
import sys
import tarfile

ROOT = Path(__file__).resolve().parents[1]
RUNTIME = ("dpkt", "pyserial", "zeroconf", "numpy", "pillow", "opencv-python")


def sha256(path):
    with path.open("rb") as stream:
        return hashlib.file_digest(stream, "sha256").hexdigest()


def verify_archives(manifest, root):
    checked = []
    for entry in manifest["sources"]:
        if Path(entry["filename"]).name != entry["filename"]:
            raise ValueError("Source archive name must be a plain filename")
        digest = sha256(root / entry["filename"])
        if digest != entry["sha256"]:
            raise ValueError(f"Source hash mismatch: {entry['filename']}")
        checked.append({"name": entry["name"], "version": entry["version"], "filename": entry["filename"], "sha256": digest})
    return checked


def check_wheel(dist):
    record = dist.read_text("RECORD")
    if record is None:
        raise ValueError(f"{dist.metadata['Name']} has no wheel RECORD")
    checked, failures = 0, []
    for row in csv.reader(io.StringIO(record)):
        if len(row) < 2 or not row[1].startswith("sha256="):
            continue  # RECORD and generated bytecode have no upstream digest.
        path = Path(dist.locate_file(row[0]))
        if not path.is_file():
            failures.append({"path": row[0], "error": "missing"})
            continue
        digest = base64.urlsafe_b64encode(bytes.fromhex(sha256(path))).rstrip(b"=").decode()
        checked += 1
        if digest != row[1].split("=", 1)[1]:
            failures.append({"path": row[0], "error": "modified"})
    return {"name": dist.metadata["Name"], "version": dist.version,
            "hashed_files_checked": checked, "failures": failures,
            "evidence": "Installed files match their wheel RECORD; this is not independent authentication of the upstream wheel"}


def compare_source_files(dist, archive_path):
    matches, differences, absent = [], [], []
    with tarfile.open(archive_path) as archive:
        members = {m.name.partition("/")[2]: m for m in archive if m.isfile()}
        for item in dist.files or ():
            name = str(item)
            if not name.endswith((".py", ".pyx", ".pxd")):
                continue
            member = members.get("src/" + name) or members.get(name)
            if member is None:
                absent.append(name)
            elif archive.extractfile(member).read() == Path(dist.locate_file(item)).read_bytes():
                matches.append(name)
            else:
                differences.append(name)
    return {"name": dist.metadata["Name"], "version": dist.version,
            "matching_files": matches, "different_files": differences, "files_absent_from_sdist": absent,
            "binary_rebuild_test": "not performed"}


def opencv_evidence(archive_path, runtime):
    with tarfile.open(archive_path) as archive:
        members = {m.name.partition("/")[2]: m for m in archive if m.isfile()}
        def read(name):
            return archive.extractfile(members[name]).read().decode("utf-8")
        recipe = read("docker/manylinux2014/Dockerfile_x86_64")
        setup = read("setup.py")
        line = next(line for line in recipe.splitlines()
                    if "PKG_CONFIG_PATH=" in line and "./configure --prefix=" in line)
        arguments = shlex.split(line.split("./configure ", 1)[1].split(" &&", 1)[0].replace("$HOME", "/root"))
        observed = runtime.get("ffmpeg", [])
        configuration_matches = bool(observed) and all(
            shlex.split(item.get("configuration", "")) == arguments for item in observed)
        return {
            "archive_patch_files": sorted(name for name in members if "/patches/" in name or name.startswith("patches/")),
            "wheel_packaging_patches": [
                {"path": "patches/patchQtPlugins", "sha256": hashlib.sha256(read("patches/patchQtPlugins").encode()).hexdigest(),
                 "effect": "Patches OpenCV CMake installation to copy Qt plugins/fonts; it does not patch Qt's library source",
                 "selected_profile": "Linux non-headless CI wheel", "applies_to_reviewed_profile": bool(re.search(r"GUI:\s+QT5", runtime["opencv_build"]))},
                {"path": "patches/patchOpenEXR", "sha256": hashlib.sha256(read("patches/patchOpenEXR").encode()).hexdigest(),
                 "selected_profile": "32-bit Linux wheel", "applies_to_reviewed_profile": False},
            ],
            "recipe": "docker/manylinux2014/Dockerfile_x86_64",
            "recipe_sha256": hashlib.sha256(recipe.encode()).hexdigest(),
            "setup_sha256": hashlib.sha256(setup.encode()).hexdigest(),
            "ffmpeg_configuration_matches_recipe": configuration_matches,
            "ffmpeg_version_matches_recipe": bool(observed) and all(item.get("version") == "8.1.1" for item in observed),
            "ffmpeg_recipe_version": "8.1.1" if "ARG FFMPEG_VERSION=8.1.1" in recipe else "needs-review",
            "qt_recipe_version": "5.15.19" if "ARG QT_VERSION=5.15.19" in recipe else "needs-review",
            "qt_runtime_version_matches_recipe": bool(re.search(r"QT:\s+YES \(ver 5\.15\.19(?:\s|\))", runtime["opencv_build"])),
            "scope": "Observed Linux x86_64 non-headless wheel; vendored patches and native rebuilds require separate review",
        }


def native_sources(inventory):
    groups = {}
    for binary in inventory["binaries"]:
        owner = binary.get("owner")
        if not owner:
            continue
        name = owner.get("source_package") or owner["name"]
        version = owner.get("source_version") or owner["version"]
        key = (owner["kind"], name, version)
        if key not in groups:
            groups[key] = {"kind": key[0], "source_package": name, "source_version": version,
                           "binaries": [], "source_collection": "pending"}
            if owner["kind"] == "debian-package":
                groups[key]["download_arguments"] = ["apt-get", "source", "--download-only", f"{name}={version}"]
        groups[key]["binaries"].append(binary["path"])
    return sorted(groups.values(), key=lambda item: (item["kind"], item["source_package"]))


def ubuntu_manifest(packages, source_list, lists):
    options = ["-o", f"Dir::Etc::sourcelist={source_list}", "-o", "Dir::Etc::sourceparts=-",
               "-o", f"Dir::State::lists={lists}"]
    entries = []
    for package in packages:
        if package["kind"] != "debian-package":
            continue
        name, version = package["source_package"], package["source_version"]
        result = subprocess.run(["apt-cache", *options, "showsrc", name], capture_output=True, text=True, check=True)
        block = next((b for b in result.stdout.split("\n\n") if f"\nVersion: {version}\n" in "\n" + b + "\n"), None)
        if block is None:
            raise ValueError(f"Exact Ubuntu source version is not indexed: {name} {version}")
        directory = next(line.split(": ", 1)[1] for line in block.splitlines() if line.startswith("Directory: "))
        for line in block.split("Checksums-Sha256:\n", 1)[1].splitlines():
            if not line.startswith(" "):
                break
            checksum, size, filename = line.split()
            entries.append({"name": name, "version": version, "filename": filename,
                            "url": f"https://archive.ubuntu.com/ubuntu/{directory}/{filename}",
                            "sha256": checksum, "size": int(size),
                            "correspondence": "Exact source version indexed by Ubuntu APT, including distro patch archives; use freshly signature-verified indexes"})
    return {"schema_version": 1, "purpose": "Exact Ubuntu source packages for the supplied native inventory", "sources": entries}


def check_debian_binaries(inventory, toc_path):
    originals = {name: Path(source) for name, source, kind in ast.literal_eval(toc_path.read_text())[0]
                 if kind in {"BINARY", "EXTENSION"}}
    checks = []
    for entry in inventory["binaries"]:
        owner = entry.get("owner")
        if not owner or owner["kind"] != "debian-package":
            continue
        sums = Path("/var/lib/dpkg/info") / (owner["name"] + ".md5sums")
        source = originals[entry["path"]]
        expected = dict((line.split(maxsplit=1)[1].lstrip("/"), line.split(maxsplit=1)[0])
                        for line in sums.read_text().splitlines()) if sums.exists() else {}
        wanted = expected.get(str(source.resolve()).lstrip("/")) or expected.get(str(source).lstrip("/"))
        with source.open("rb") as stream:
            actual = hashlib.file_digest(stream, "md5").hexdigest()
        checks.append({"path": entry["path"], "package": owner["name"], "source_version": owner["source_version"],
                       "package_record_matches": actual == wanted if wanted else None,
                       "native_input_sha256_matches": sha256(source) == entry["sha256"]})
    return checks


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--sources", type=Path, required=True)
    parser.add_argument("--notices", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--native-toc", type=Path, help="verify Debian native inputs against installed package records")
    parser.add_argument("--ubuntu-source-list", type=Path, help="source-only APT configuration used for signed indexes")
    parser.add_argument("--ubuntu-source-lists", type=Path, help="directory containing those APT indexes")
    parser.add_argument("--ubuntu-manifest", type=Path, help="download manifest generated from those indexes")
    parser.add_argument("--ubuntu-sources", type=Path, help="verify the downloaded Ubuntu source files")
    args = parser.parse_args()
    if sys.platform != "linux" or platform.machine().lower() not in {"x86_64", "amd64"}:
        parser.error("This review profile covers Linux x86_64 only")
    if bool(args.ubuntu_source_list) != bool(args.ubuntu_source_lists):
        parser.error("Provide both --ubuntu-source-list and --ubuntu-source-lists")
    if (args.ubuntu_source_list or args.ubuntu_sources) and not args.ubuntu_manifest:
        parser.error("Ubuntu index/source checks require --ubuntu-manifest")
    manifest_path = ROOT / "third_party/source-manifest.json"
    manifest = json.loads(manifest_path.read_text())
    archives = {entry["name"]: args.sources / entry["filename"] for entry in manifest["sources"]}
    archive_checks = verify_archives(manifest, args.sources)
    wheels = [check_wheel(distribution(name)) for name in RUNTIME]
    versions = {entry["name"].lower(): entry["version"] for entry in manifest["sources"]}
    if any(item["version"] != versions[item["name"].lower()] for item in wheels):
        raise ValueError("Installed runtime versions do not match the source manifest")
    source = compare_source_files(distribution("zeroconf"), archives["zeroconf"])
    runtime_path = args.notices / "runtime-build.json"
    native_path = args.notices / "native-inventory.json"
    report = {
        "schema_version": 1, "scope": "local Linux source-correspondence evidence; final installer review remains open",
        "input_hashes": {"source_manifest": sha256(manifest_path), "runtime_build": sha256(runtime_path), "native_inventory": sha256(native_path)},
        "archives": archive_checks, "installed_wheels": wheels, "zeroconf_sources": source,
        "opencv": opencv_evidence(archives["opencv-python"], json.loads(runtime_path.read_text())),
        "native_source_packages": native_sources(json.loads(native_path.read_text())),
    }
    import numpy
    config = numpy.__config__.CONFIG
    report["numpy_build"] = {
        "compilers": config["Compilers"],
        "blas": {key: value for key, value in config["Build Dependencies"]["blas"].items()
                 if key in {"name", "version", "openblas configuration"}},
        "vendored_gnu_runtime_source_review": "pending; NumPy's C compiler version alone does not identify the source revision of its prebuilt BLAS/GNU libraries",
    }
    if args.native_toc:
        report["debian_binary_integrity"] = check_debian_binaries(json.loads(native_path.read_text()), args.native_toc)
    if args.ubuntu_source_list:
        entries = ubuntu_manifest(report["native_source_packages"], args.ubuntu_source_list, args.ubuntu_source_lists)
        args.ubuntu_manifest.write_text(json.dumps(entries, indent=2) + "\n")
    if args.ubuntu_sources:
        entries = json.loads(args.ubuntu_manifest.read_text())
        report["ubuntu_source_files"] = verify_archives(entries, args.ubuntu_sources)
        report["input_hashes"]["ubuntu_source_manifest"] = sha256(args.ubuntu_manifest)
        provided = {(entry["name"], entry["version"]) for entry in entries["sources"]}
        for package in report["native_source_packages"]:
            if package["kind"] == "debian-package" and (package["source_package"], package["source_version"]) in provided:
                package["source_collection"] = "downloaded and hash-verified, including distro patch archives"
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(report, indent=2) + "\n")
    binary_failures = any(item["package_record_matches"] is not True or not item["native_input_sha256_matches"]
                          for item in report.get("debian_binary_integrity", []))
    recipe_failures = not all(report["opencv"][name] for name in (
        "ffmpeg_configuration_matches_recipe", "ffmpeg_version_matches_recipe", "qt_runtime_version_matches_recipe"))
    if binary_failures or recipe_failures or any(item["failures"] for item in wheels) or source["different_files"] or source["files_absent_from_sdist"]:
        raise SystemExit("Source/wheel differences need review; see report")
    print(f"Verified {len(wheels)} installed wheel records and {len(source['matching_files'])} zeroconf source files; wrote {args.output}")


if __name__ == "__main__":
    main()
